// Renders assets/icon.svg to assets/icon.png, which electron-builder turns into the Windows icon, and to the
// 64x64 server-icon.png every test server shows in the multiplayer list (src/main/server-icon.ts).
// Run with: npx electron scripts/icon.cjs
const { app, BrowserWindow } = require("electron");
const { readFileSync, writeFileSync } = require("node:fs");
const { join } = require("node:path");

app.whenReady().then(() => {
    const svg = readFileSync(join(__dirname, "../assets/icon.svg"), "utf8");
    // Offscreen, because a hidden window never paints and so never gives capturePage a frame.
    const window = new BrowserWindow({ width: 512, height: 512, show: false, transparent: true, frame: false, webPreferences: { offscreen: true } });
    window.webContents.once("paint", (_event, _dirty, image) => {
        writeFileSync(join(__dirname, "../assets/icon.png"), image.resize({ width: 512, height: 512 }).toPNG());
        // Inlined as base64 so it needs no file next to the packaged app, and tests import it like any module.
        const server = image.resize({ width: 64, height: 64, quality: "best" }).toPNG().toString("base64");
        writeFileSync(join(__dirname, "../src/main/server-icon.ts"), [
            "// Generated by scripts/icon.cjs from assets/icon.svg. Minecraft wants exactly 64x64.",
            `export const SERVER_ICON = Buffer.from("${server}", "base64");`,
            "",
        ].join("\n"));
        app.quit();
    });
    void window.loadURL(`data:text/html,<style>html,body{margin:0;background:transparent;overflow:hidden}</style>${encodeURIComponent(svg)}`);
});
